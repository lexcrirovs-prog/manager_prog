"""Автоматическое определение приоритета сделки по тексту примечания.

Логика приоритетов (HIGH > MEDIUM > LOW):

  HIGH   — в тексте есть признаки конкуренции: упомянуты конкуренты,
            сравнение цен, тендер, борьба за поставку.
  MEDIUM — был конкретный запрос на котёл или оборудование, но конкурентов нет.
  LOW    — холодный контакт, рассылка, ответ «рассмотрим в будущем»;
           также дефолт, если ничего не найдено.
"""

import re

from app.database.models import LeadPriority

# ── Паттерны для HIGH: конкуренция, тендер, ценовая борьба ──────────────────
_HIGH_PATTERNS = [
    r"\bконкурент",            # конкурент / конкуренты / конкурентный
    r"конкуренц",              # конкуренция / конкурентоспособн...
    r"другой\s+поставщик",
    r"другие\s+поставщики",
    r"другое\s+предложение",
    r"альтернативн\w+\s+предложен",
    r"\bтендер",               # тендер / тендерная документация
    r"сравнива\w+\s+(цен|предложен)",
    r"дешевле|дороже",         # ценовое сравнение
    r"борьб[аую]\s+за",        # борьба за контракт
    r"перебивают\s+цену",
    r"уход[ит]+\s+к\s+другим",
    r"смотрят\s+(?:ещё|других|другие)",
]

# ── Паттерны для MEDIUM: запрос на оборудование ──────────────────────────────
_MEDIUM_PATTERNS = [
    r"\bзапрос\b",             # был запрос
    r"\bкотл[её]",             # котёл / котлы / котлов
    r"\bкп\s+на\b",            # КП на ...
    r"просчита[тьлю]",         # просчитать / просчитали
    r"коммерческ\w+\s+предложен",
    r"техническ\w+\s+задани",  # техническое задание
    r"\bтз\s+на\b",
    r"интересует\s+котл",
    r"нужен\s+котл",
    r"нужн[ыа]\s+котл",
    r"хотят\s+котл",
    r"запрашива\w+",           # запрашивали / запрашивает
    r"прислали\s+(тз|запрос|задани)",
]

# ── Паттерны LOW (для информации — дефолт и без них) ─────────────────────────
_LOW_PATTERNS = [
    r"холодн\w+\s+(звонок|обзвон)",
    r"рассылк",
    r"на\s+будущее",
    r"рассмотр[ие]\w+\s+в\s+будущ",
    r"пока\s+не\s+нужно",
    r"не\s+актуально",
    r"не\s+рассматривают",
]


def detect_lead_priority(notes: str) -> LeadPriority:
    """Возвращает LeadPriority по тексту примечания.

    Порядок проверки: HIGH → MEDIUM → LOW.
    Если текст пустой или ни один паттерн не сработал — возвращает LOW.
    """
    if not notes or not notes.strip():
        return LeadPriority.LOW

    text = notes.lower()

    for pattern in _HIGH_PATTERNS:
        if re.search(pattern, text):
            return LeadPriority.HIGH

    for pattern in _MEDIUM_PATTERNS:
        if re.search(pattern, text):
            return LeadPriority.MEDIUM

    return LeadPriority.LOW
